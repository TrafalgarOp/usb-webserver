// Application router for the versioned JSON API. It resolves a parsed request
// line to a response body and status. It parses pin names and asks the GPIO
// module for validity and metadata; it never touches hardware directly and
// never allocates.
//

#ifndef USB_WEBSERVER_API_ROUTER_H
#define USB_WEBSERVER_API_ROUTER_H

#include <stdint.h>

/* Maximum JSON body the router will produce. The transport must provide a
 * body buffer of at least this size. */
#define API_ROUTE_BODY_MAX 2048

/*
 * The request as seen by the router. The transport has already validated HTTP
 * framing, so `body` is a complete, bounded request body (not a stream), and
 * `body_present` distinguishes "no Content-Length given" from an explicit
 * `Content-Length: 0`.
 */
typedef struct
{
    const char *body;          /* request body bytes (never NULL) */
    uint16_t    body_len;      /* body length in bytes */
    uint8_t     body_present;  /* 1 if the client supplied Content-Length */
    const char *content_type;  /* raw Content-Type value, or NULL if absent */
} API_Request_t;

typedef struct
{
    int         status;         /* HTTP status code */
    const char *reason;         /* reason phrase */
    const char *extra_headers;  /* e.g. "Allow: GET\r\n", or NULL */

    /*
     * Streaming descriptors. stream_bytes > 0 tells the transport to send a
     * body of that many generated bytes over the same connection instead of
     * using the buffered `body` output; content_type is the media type for
     * that body. Both are zeroed for ordinary buffered responses.
     */
    uint32_t    stream_bytes;
    const char *content_type;
} API_Route_t;

/*
 * Resolve an HTTP request to a response body.
 *
 * `method` is NUL-terminated and read-only. `path` is NUL-terminated, owned by
 * the caller, and may be modified in place (the router splits a "/value"
 * suffix). The JSON body is written into body[0..cap) and its length in bytes
 * is returned. `meta` receives the status, reason phrase, and any extra
 * headers.
 *
 * The caller must treat the returned length as authoritative and must not
 * assume the body is NUL-terminated.
 */
uint16_t API_Router_Handle(const char *method, char *path,
                           const API_Request_t *req,
                           API_Route_t *meta,
                           char *body, uint16_t cap);

#endif // USB_WEBSERVER_API_ROUTER_H
